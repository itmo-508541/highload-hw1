<?php

declare(strict_types=1);

// Собирает дамп env (`.env.local.php`) для demo-режима: tools/env-dump.php <каталог-dotenv> <файл-дампа>.
//
// Цепочка — явный список в порядке loadEnv: `.env` → `.env.local` → `.env.prod` → `.env.prod.local` (оба `.local` — если есть),
// окружение — APP_ENV процесса. Не bootEnv: тот прочитал бы прежний дамп через шим `.env.local.php`. Не loadEnv: без `.env`
// он молча берёт `.env.dist`, а `.env` обязателен.

require dirname(__DIR__).'/vendor/autoload.php';

use Symfony\Component\Dotenv\Dotenv;

if (3 !== $argc) {
    fwrite(\STDERR, "Usage: php tools/env-dump.php <dotenv-dir> <dump-file>\n");
    exit(2);
}

[, $dotenvDir, $dumpFile] = $argv;

try {
    $env = $_SERVER['APP_ENV'] ?? throw new LogicException('APP_ENV is missing.');

    $paths = [$dotenvDir.'/.env'];
    if (is_file($dotenvDir.'/.env.local')) {
        $paths[] = $dotenvDir.'/.env.local';
    }
    $paths[] = $dotenvDir.'/.env.'.$env;
    if (is_file($dotenvDir.'/.env.'.$env.'.local')) {
        $paths[] = $dotenvDir.'/.env.'.$env.'.local';
    }

    // Как в DotenvDumpCommand: в дамп попадают только APP_ENV и значения из файлов, а файлы перекрывают
    // переменные контейнера — все уже известные имена объявлены «загруженными из dotenv».
    unset($_SERVER['APP_ENV']);
    $_ENV = ['APP_ENV' => $env];
    $_SERVER['SYMFONY_DOTENV_VARS'] = implode(',', array_keys($_SERVER));

    new Dotenv()->load(...$paths);
    unset($_ENV['SYMFONY_DOTENV_VARS'], $_ENV['SYMFONY_DOTENV_PATH']);

    $vars = var_export($_ENV, true);
    $content = <<<EOF
        <?php

        // This file was generated by tools/env-dump.php

        return {$vars};

        EOF;

    // Через временный файл: читатель дампа не увидит его недописанным.
    $tmpFile = $dumpFile.'.tmp';
    if (false === file_put_contents($tmpFile, $content) || !rename($tmpFile, $dumpFile)) {
        throw new RuntimeException(sprintf('Cannot write "%s".', $dumpFile));
    }
} catch (Throwable $e) {
    fwrite(\STDERR, $e->getMessage()."\n");
    exit(1);
}

fwrite(\STDOUT, sprintf("Dumped %s for the %s environment.\n", $dumpFile, $env));
